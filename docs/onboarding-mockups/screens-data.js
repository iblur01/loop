/**
 * Helper bilingue : retourne le texte dans la langue choisie ("fr", "en", ou "bilingual" avec sous-ligne EN).
 */
window.tText = function (fr, en, lang) {
  if (lang === 'en') return en;
  if (lang === 'bilingual') {
    return fr + '<span class="en-parallel" lang="en">' + en + '</span>';
  }
  return fr;
};

window.tBtn = function (fr, en, lang) {
  if (lang === 'en') return '<span>' + en + '</span>';
  if (lang === 'bilingual') {
    return '<span>' + fr + '</span><span class="btn-en-sub" lang="en">' + en + '</span>';
  }
  return '<span>' + fr + '</span>';
};

